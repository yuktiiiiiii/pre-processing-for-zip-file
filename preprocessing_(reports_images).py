import os
import numpy as np
import cv2
import matplotlib.pyplot as plt
import seaborn as sns
import pandas as pd
from sklearn.preprocessing import MinMaxScaler
from sklearn.decomposition import PCA
from sklearn.cluster import KMeans
from sklearn.impute import SimpleImputer
from imblearn.combine import SMOTEENN
from sklearn.model_selection import train_test_split
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense, LSTM, Reshape
from tensorflow.keras.callbacks import EarlyStopping

# Set path and limits
image_path = "/content/preprocessed_images"
max_images = 500  # Limit images for Colab safety
image_size = (64, 64)  # Resize to reduce memory

# Load and resize grayscale images
images = []
labels_placeholder = []
for i, img_file in enumerate(os.listdir(image_path)):
    if i >= max_images:
        break
    img_full_path = os.path.join(image_path, img_file)
    img = cv2.imread(img_full_path, cv2.IMREAD_GRAYSCALE)
    if img is not None:
        img_resized = cv2.resize(img, image_size)
        images.append(img_resized.astype(np.float32))  # use float32 for efficiency
        labels_placeholder.append(i % 5)  # Dummy labels for clustering (replace with actual if available)

images = np.array(images)
if images.size == 0:
    print("No images found.")
else:
    print(f"Loaded {len(images)} images with shape {images.shape}")

    # Flatten and clean
    flat_images = images.reshape(len(images), -1)
    imputer = SimpleImputer(strategy='mean')
    cleaned_data = imputer.fit_transform(flat_images)

    # KMeans clustering
    kmeans = KMeans(n_clusters=5, random_state=42, n_init=10)
    labels = kmeans.fit_predict(cleaned_data)

    # Remove single-instance clusters
    unique_labels, counts = np.unique(labels, return_counts=True)
    valid_clusters = unique_labels[counts > 1]
    mask = np.isin(labels, valid_clusters)
    cleaned_data = cleaned_data[mask]
    labels = labels[mask]

    if len(cleaned_data) == 0:
        print("No data left after filtering.")
    else:
        # Dimensionality reduction
        pca = PCA(n_components=30)
        reduced_data = pca.fit_transform(cleaned_data)

        # Scaling
        scaler = MinMaxScaler()
        scaled_data = scaler.fit_transform(reduced_data)

        # Hybrid oversampling
        sampler = SMOTEENN(random_state=42)
        oversampled_data, oversampled_labels = sampler.fit_resample(scaled_data, labels)

        # Visualization
        plt.figure(figsize=(6, 4))
        sns.histplot(oversampled_data[:, 0], kde=True)
        plt.title("Feature 1 Distribution")
        plt.tight_layout()
        plt.show()

        # Train/test split
        X_train, X_test, y_train, y_test = train_test_split(
            oversampled_data, oversampled_labels, test_size=0.2, random_state=42
        )

        early_stop = EarlyStopping(monitor='loss', patience=3, restore_best_weights=True)

        # Dense model (formerly CNN)
        cnn_model = Sequential([
            Dense(64, activation='relu', input_shape=(X_train.shape[1],)),
            Dense(32, activation='relu'),
            Dense(len(np.unique(y_train)), activation='softmax')
        ])
        cnn_model.compile(optimizer='adam', loss='sparse_categorical_crossentropy', metrics=['accuracy'])

        print("Training Dense model...")
        cnn_model.fit(X_train, y_train, epochs=10, batch_size=16, callbacks=[early_stop], verbose=1)

        # RNN model
        rnn_model = Sequential([
            Reshape((X_train.shape[1], 1), input_shape=(X_train.shape[1],)),
            LSTM(32, return_sequences=False),
            Dense(16, activation='relu'),
            Dense(len(np.unique(y_train)), activation='softmax')
        ])
        rnn_model.compile(optimizer='adam', loss='sparse_categorical_crossentropy', metrics=['accuracy'])

        print("Training RNN model...")
        rnn_model.fit(X_train, y_train, epochs=10, batch_size=16, callbacks=[early_stop], verbose=1)

        # Evaluation
        print("\nEvaluating models...")
        cnn_loss, cnn_acc = cnn_model.evaluate(X_test, y_test, verbose=0)
        rnn_loss, rnn_acc = rnn_model.evaluate(X_test, y_test, verbose=0)

        print(f"Dense Model Accuracy: {cnn_acc:.4f}")
        print(f"RNN Model Accuracy: {rnn_acc:.4f}")

        # Save outputs
        np.save("/content/cleaned_images_data.npy", oversampled_data)
        np.save("/content/oversampled_image_labels.npy", oversampled_labels)

