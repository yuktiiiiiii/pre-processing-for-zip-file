                image_filename = f"{pdf_name}_page{page_index+1}_img{img_index+1}.{image_ext}"
                image_path = os.path.join(output_dir, image_filename)

                # Save extracted image
                with open(image_path, "wb") as f:
                    f.write(image_bytes)

                # Preprocess and save
                preprocessed_path = os.path.join(preprocessed_dir, image_filename)
