import os
import fitz  # PyMuPDF
import re
import pandas as pd


def extract_text_from_pdf(pdf_path):
    """Extract text from all pages of the PDF"""
    doc = fitz.open(pdf_path)
    full_text = []

    for page_num in range(len(doc)):
        page = doc.load_page(page_num)
        text = page.get_text()
        full_text.append(text)

    doc.close()
    return full_text


def clean_text(text):
    """Clean extracted text by removing unwanted characters and multiple spaces"""
    text = re.sub(r'\s+', ' ', text)  # collapse multiple whitespace
    text = re.sub(r'[^A-Za-z0-9.,:%()\-/& ]', '', text)  # retain only meaningful chars
    return text.strip()


def process_pdf_folder(input_folder, output_csv):
    """Process all PDF files in a folder and save results to one CSV"""
    all_data = []

    for filename in os.listdir(input_folder):
        if filename.lower().endswith(".pdf"):
            file_path = os.path.join(input_folder, filename)
            print(f"Processing {filename}...")

            try:
                raw_text = extract_text_from_pdf(file_path)
                cleaned_pages = [clean_text(page) for page in raw_text]

                for page_num, content in enumerate(cleaned_pages, 1):
                    all_data.append({
                        "file_name": filename,
                        "page_number": page_num,
                        "cleaned_text": content
                    })
            except Exception as e:
                print(f" Error processing {filename}: {e}")

    df = pd.DataFrame(all_data)
    df.to_csv(output_csv, index=False, encoding='utf-8')
    print(f"\n All PDFs processed and saved to '{output_csv}'")


