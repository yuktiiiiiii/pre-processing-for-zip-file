test_encodings = bert_encode(X_test_text)

bert_model = TFDistilBertModel.from_pretrained("distilbert-base-uncased")

# Define model inputs (Shapes match the bert_encode max_len)
input_ids = Input(shape=(128,), dtype=tf.int32, name="input_ids")
attention_mask = Input(shape=(128,), dtype=tf.int32, name="attention_mask")

# The Lambda layer expects input with shapes matching the Input layers
# Add output_shape argument to Lambda layer
embedding = Lambda(lambda inputs: bert_model(inputs[0], attention_mask=inputs[1])[0], output_shape=(128, 768))([input_ids, attention_mask])


x = GlobalAveragePooling1D()(embedding)
x = Dense(64, activation='relu')(x)

output = Dense(len(np.unique(df['label_encoded'])), activation='softmax')(x)

transformer_model = Model(inputs=[input_ids, attention_mask], outputs=output)
transformer_model.compile(optimizer='adam', loss='sparse_categorical_crossentropy', metrics=['accuracy'])

