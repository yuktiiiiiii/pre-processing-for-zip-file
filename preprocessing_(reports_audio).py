# Transformer Model with DistilBERT
bert_tokenizer = DistilBertTokenizer.from_pretrained('distilbert-base-uncased')

def bert_encode(texts, max_len=128):
    # Change padding=True to padding='max_length'
    return bert_tokenizer(texts.tolist(), padding='max_length', truncation=True, max_length=max_len, return_tensors='tf')

# Use the text Series directly for encoding
