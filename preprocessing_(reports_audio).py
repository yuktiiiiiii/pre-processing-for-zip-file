from transformers import TFDistilBertModel, DistilBertTokenizer
from sklearn.model_selection import train_test_split # Make sure this is imported
from sklearn.metrics import accuracy_score # Make sure this is imported
import pandas as pd # Make sure pandas is imported as df is used

df = pd.read_csv("/content/preprocessed_audio_transcriptions.csv")

if 'label' not in df.columns:
    df['label'] = np.random.choice(['class1', 'class2'], size=len(df))  # Random labels for demo

# Encode labels
if 'label_encoded' not in df.columns:
    from sklearn.preprocessing import LabelEncoder
    label_encoder = LabelEncoder()
    df['label_encoded'] = label_encoder.fit_transform(df['label'])

# Assuming tokenizer and padded_sequences are available. Re-create if necessary.
from tensorflow.keras.preprocessing.text import Tokenizer
from tensorflow.keras.preprocessing.sequence import pad_sequences

tokenizer = Tokenizer(num_words=5000, oov_token='<OOV>')
tokenizer.fit_on_texts(df['processed_text'])
sequences = tokenizer.texts_to_sequences(df['processed_text'])
# Padded sequences for CNN/RNN (length 100 as before)
padded_sequences = pad_sequences(sequences, maxlen=100, padding='post')


train_indices, test_indices = train_test_split(df.index, test_size=0.2, random_state=42)
X_train_text = df.loc[train_indices, 'processed_text']
y_train = df.loc[train_indices, 'label_encoded'].values

X_test_text = df.loc[test_indices, 'processed_text']
y_test = df.loc[test_indices, 'label_encoded'].values

# Also get the padded sequences for the CNN/RNN models using these indices
X_train_padded = padded_sequences[train_indices]
X_test_padded = padded_sequences[test_indices]


# CNN Model (Use X_train_padded and X_test_padded)
cnn_model = Sequential([
    Embedding(input_dim=5000, output_dim=64, input_length=100),
    Conv1D(128, 5, activation='relu'),
    MaxPooling1D(pool_size=2),
    Flatten(),
    Dense(64, activation='relu'),
    Dense(len(np.unique(df['label_encoded'])), activation='softmax')
])
cnn_model.compile(optimizer='adam', loss='sparse_categorical_crossentropy', metrics=['accuracy'])
